drop policy if exists profiles_self_or_owner on public.profiles;
create policy profiles_self_or_owner on public.profiles for select to authenticated using (id=auth.uid() or public.is_owner());

drop policy if exists content_public_read on public.site_content;
create policy content_public_read on public.site_content for select to anon, authenticated using (true);
drop policy if exists content_admin_write on public.site_content;
create policy content_admin_write on public.site_content for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists prices_public_read on public.price_items;
create policy prices_public_read on public.price_items for select to anon, authenticated using (active=true or public.is_admin());
drop policy if exists prices_admin_write on public.price_items;
create policy prices_admin_write on public.price_items for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists gallery_public_read on public.gallery_items;
create policy gallery_public_read on public.gallery_items for select to anon, authenticated using (active=true or public.is_admin());
drop policy if exists gallery_admin_write on public.gallery_items;
create policy gallery_admin_write on public.gallery_items for all to authenticated using (public.is_admin()) with check (public.is_admin());

